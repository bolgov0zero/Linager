// netplanFileRe is the allowed name of a netplan file the panel may write.
var netplanFileRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,60}\.yaml$`)

// NetplanFile is one YAML file of /etc/netplan for the panel's editor.
type NetplanFile struct {
	Name      string `json:"name"`
	Text      string `json:"text"`
	CloudInit bool   `json:"cloud_init"` // generated by cloud-init, which may overwrite it
}

// isCloudInitFile recognises the header cloud-init writes into netplan files it generates.
func isCloudInitFile(name, text string) bool {
	head := text
	if len(head) > 600 {
		head = head[:600]
	}
	return strings.Contains(head, "cloud-init") || strings.Contains(head, "datasource") || strings.HasPrefix(name, "50-cloud-init")
}

// netplanFiles lists /etc/netplan/*.yaml in netplan's own (alphabetical) order.
func (m *netModule) netplanFiles() []NetplanFile {
	paths, _ := filepath.Glob(filepath.Join(m.npDir, "*.yaml"))
	sort.Strings(paths)
	out := make([]NetplanFile, 0, len(paths))
	for _, p := range paths {
		text := read(p)
		out = append(out, NetplanFile{Name: filepath.Base(p), Text: text, CloudInit: isCloudInitFile(filepath.Base(p), text)})
	}
	return out
}

// netplanEffective returns the merged configuration of all files (`netplan get`), empty when unavailable.
func (m *netModule) netplanEffective(ctx context.Context) string {
	cctx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()
	out, err := m.run(cctx, "netplan", "get")
	if err != nil {
		return ""
	}
	return string(out)
}

// applyNetplan replaces (or creates) one netplan file. The new text is checked with `netplan generate` before
// anything is applied; then `netplan apply` runs inside the pending flow, so the old file comes back by itself
// unless the administrator confirms in time.
func (m *netModule) applyNetplan(ctx context.Context, id, name, text string) (any, error) {
	if !netplanFileRe.MatchString(name) {
		return nil, errors.New("invalid file name")
	}
	text = strings.ReplaceAll(text, "\r\n", "\n")
	if strings.TrimSpace(text) == "" || len(text) > maxRawConfig || strings.ContainsRune(text, 0) {
		return nil, errors.New("the file is empty, too large or not text")
	}
	text = strings.TrimRight(text, "\n") + "\n"
	path := filepath.Join(m.npDir, name)
	oldBytes, readErr := os.ReadFile(path) //nolint:gosec // a netplan file chosen by name from a strict pattern
	existed := readErr == nil
	if existed && string(oldBytes) == text {
		return nil, errors.New("nothing changed")
	}
	if err := os.MkdirAll(m.dir, 0o700); err != nil {
		return nil, err
	}
	bak := filepath.Join(m.dir, "net-"+id+".netplan.bak")
	if existed {
		if err := os.WriteFile(bak, oldBytes, 0o600); err != nil { //nolint:gosec // bak is inside the agent data dir, named from the change id
			return nil, err
		}
	}
	restore := func() {
		if existed {
			_ = os.WriteFile(path, oldBytes, 0o600) //nolint:gosec // path is /etc/netplan plus a name checked by netplanFileRe
		} else {
			_ = os.Remove(path)
		}
		_ = os.Remove(bak)
	}
	if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
		restore()
		return nil, err
	}
	cctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	out, err := m.run(cctx, "netplan", "generate")
	cancel()
	if err != nil {
		restore()
		return nil, fmt.Errorf("netplan generate: %s", lastLine(string(out), err.Error()))
	}
	data := netPendingData{Netplan: true, NpPath: path, NpBak: bak, NpExisted: existed}
	deadline, err := m.pend.Begin(id, "network", data, PendingWindow)
	if err != nil {
		restore()
		return nil, err
	}
	actx, acancel := context.WithTimeout(ctx, 25*time.Second)
	defer acancel()
	if out, err := m.run(actx, "netplan", "apply"); err != nil {
		m.pend.Abort(id)
		return nil, fmt.Errorf("netplan apply: %s", lastLine(string(out), err.Error()))
	}
	return map[string]any{"id": id, "deadline": deadline}, nil
}

func (m *netModule) netplanRollback(d netPendingData) error {
	if d.NpExisted {
		old, err := os.ReadFile(d.NpBak) //nolint:gosec // our own backup file
		if err != nil {
			return err
		}
		if err := os.WriteFile(d.NpPath, old, 0o600); err != nil { //nolint:gosec // NpPath was built from a checked name when the change began
			return err
		}
	} else {
		_ = os.Remove(d.NpPath)
	}
	_ = os.Remove(d.NpBak)
	ctx, cancel := context.WithTimeout(context.Background(), 25*time.Second)
	defer cancel()
	if out, err := m.run(ctx, "netplan", "apply"); err != nil {
		return fmt.Errorf("restoring netplan: %s", lastLine(string(out), err.Error()))
	}
	return nil
}

func (m *netModule) netplanCommit(d netPendingData) error {
	if d.NpExisted {
		if old, err := os.ReadFile(d.NpBak); err == nil { //nolint:gosec // our own backup file
			_ = os.WriteFile(filepath.Join(m.dir, "netplan-"+filepath.Base(d.NpPath)+".bak-"+time.Now().Format("20060102-150405")), old, 0o600)
		}
	}
	_ = os.Remove(d.NpBak)
	return nil
}
